// sources - the freqtrade-strategies repository, QuantConnect's forum and research posts, and broker / trading-education
// guides - each with its exact rules (E = stated or implemented in the source, I = our interpretation, A = our
// adaptation), evidence locations, implementation-risk checks and, where the rules are complete, a fee-honest backtest
// split into development and out-of-sample windows. Research only: nothing here trades, and nothing is "validated".
// Data: ./webSourcesData.ts, generated by backend/research/web_sources_2026_11/ws_export.py.
import { useMemo, useState } from "react";
import GlassPanel from "../../components/GlassPanel";
import { ScrollBox } from "../../components/TopScrollbar";
import { WS, WS_META, WS_OTHER, type WsRecord, type WsStats } from "./webSourcesData";

const STATUS_LABEL: Record<string, string> = {
  PAPER_TRADING_CANDIDATE: "Paper-trading candidate", BACKTESTED: "Backtested", READY_FOR_BACKTEST: "Ready for backtest",
  READY_FOR_IMPLEMENTATION: "Ready for implementation", BLOCKED: "Blocked", NEEDS_CLARIFICATION: "Needs clarification",
  REJECTED: "Rejected", DISCOVERED: "Discovered",
};
const STATUS_TONE: Record<string, string> = {
  PAPER_TRADING_CANDIDATE: "ws-st-good", BACKTESTED: "ws-st-mid", READY_FOR_BACKTEST: "ws-st-mid", READY_FOR_IMPLEMENTATION: "ws-st-warn",
  BLOCKED: "ws-st-warn", NEEDS_CLARIFICATION: "ws-st-warn", REJECTED: "ws-st-bad", DISCOVERED: "ws-st-mid",
};
const GROUPS = [{ id: "all", label: "All" }, { id: "crypto", label: "Crypto" }, { id: "gold", label: "Gold" }, { id: "general", label: "General markets" }];
const TAG = { E: "Stated or implemented in the source", I: "Our interpretation of the source", A: "Our adaptation or assumption" } as Record<string, string>;

const usd = (n?: number | null) => (n == null ? "–" : `${n < 0 ? "−" : ""}$${Math.abs(Math.round(n)).toLocaleString("en-US")}`);
const pc = (n?: number | null, d = 1) => (n == null ? "–" : `${n.toFixed(d)}%`);
const num = (n?: number | null, d = 2) => (n == null ? "–" : n.toFixed(d));
const tone = (n?: number | null) => (n == null ? "" : n > 0 ? "ws-pos" : n < 0 ? "ws-neg" : "");

function StatsRow({ label, s, note }: { label: string; s?: WsStats | null; note?: string }) {
  if (!s) return null;
  if (!s.trades) return (<tr><td>{label}</td><td colSpan={9} className="ws-dim">no trades{note ? ` · ${note}` : ""}</td></tr>);
  return (
    <tr>
      <td>{label}{note ? <div className="ws-dim">{note}</div> : null}</td>
      <td>{s.trades}</td>
      <td className={tone(s.net)}>{usd(s.net)}</td>
      <td className={tone(s.ret_pct)}>{pc(s.ret_pct)}</td>
      <td>{pc(s.win_rate)}</td>
      <td>{num(s.pf)}</td>
      <td className="ws-neg">{pc(s.max_dd_pct)}{s.ruined_on ? <div className="ws-dim">empty by {s.ruined_on}</div> : null}</td>
      <td className={tone(s.exp_pct)}>{pc(s.exp_pct, 3)}</td>
      <td>{num(s.t_stat)}</td>
      <td>{pc(s.exposure_pct)}</td>
    </tr>
  );
}

