            <thead><tr><th>Window</th><th>Trades</th><th>Net</th><th>Return</th><th>Win rate</th><th>Profit factor</th><th>Max drawdown</th><th>Expectancy / trade</th><th>t-stat</th><th>In market</th></tr></thead>
