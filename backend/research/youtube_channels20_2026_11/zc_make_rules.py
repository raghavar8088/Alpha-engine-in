"""Writes specs/RULES.md from the channel analyses: per strategy a heading `### <ID> <name> (<video ids>)`, its channel,
section, desk market, readiness and the rule bullets as they stand in analyses/<channel>.md ([E] stated in the video,
[I] inferred, [A] the research assumption that makes it testable); then the blocked strategies with their reasons and
the duplicates. The paper desk's library cards are built from this file (premium-paper-service/build_library.py).
    python -I zc_make_rules.py"""

from __future__ import annotations

import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

import zc_strategies as ZS  # noqa: E402

MARKET = {"NIFTY": "Nifty 50 index (1-minute data)", "BANKNIFTY": "Nifty Bank index (1-minute data)",
          "NSE5": "NSE stock pool, 5-minute candles", "NSE15": "NSE stock pool, 15-minute candles",
          "NSED": "NSE stock pool, daily candles", "NIFTY_D": "Nifty 50 daily candles", "BTCUSD": "Bitcoin (Delta BTCUSD perpetual)",
          "XAUUSD": "Gold (Delta XAUTUSD perpetual, 0.001 contracts)", "ETHUSD": "Ether (Delta ETHUSD perpetual, 0.01 contracts)"}
SECTION = {"india_intraday": "Indian Market - Equity Intraday", "india_options": "Indian Market - Options",
           "crypto": "Crypto", "gold": "Gold", "crypto_gold": "Crypto and Gold"}
READY = {"ready": "Every rule stated in the video (only the market mapping is assumed)",
         "assumptions": "Coded with documented research assumptions (the [A] lines)"}


def sections(path: Path) -> dict:
    """{strategy id: (title line, bullet lines)} of one analysis file."""
    lines = path.read_text(encoding="utf-8").splitlines()
    out, i = {}, 0
    while i < len(lines):
        m = re.match(r"^## ([A-Z]{2}-\d+)\b", lines[i])
        if not m:
            i += 1
            continue
        sid = m.group(1)
        i += 1
        title, bullets = [], []
        while i < len(lines) and not lines[i].startswith("## ") and not lines[i].startswith("### "):
            ln = lines[i]
            if ln.startswith("- ") or (bullets and ln.startswith("  ") and ln.strip()):
                bullets.append(ln)
            elif ln.strip() and not bullets:
                title.append(ln.strip())
            i += 1
        out[sid] = (" ".join(title), bullets)
    return out


def main():
    secs = {}
    for f in sorted((HERE / "analyses").glob("*.md")):
        secs.update(sections(f))
    out = ["# The 20-channel study: strategy rules", "",
           "Generated by zc_make_rules.py from analyses/<channel>.md. [E] = stated or shown in the video (with the time),",
           "[I] = inferred from the video, [A] = the research assumption that makes the rule testable. Version v1 of every",
           "strategy; a changed rule is a new version. Backtest results: results/BACKTEST.md.", ""]
    missing = []
    for sid, st in ZS.NEW.items():
        base = sid.rstrip("H") if sid.endswith("H") else sid
        sec = secs.get(base)
        if sec is None:
            missing.append(sid)
            continue
        title, bullets = sec
        out.append(f"### {sid} {st.name} ({', '.join(ZS.VIDEOS[sid])})")
        out.append("")
        out.append(f"- **Channel**: {ZS.CHANNELS[ZS.PREFIX[sid.split('-')[0]]]}")
        out.append(f"- **Section**: {SECTION[ZS.section_of(sid)]}")
        out.append(f"- **Paper desk market**: {'; '.join(MARKET[mk] for mk in st.markets)}")
        out.append(f"- **Readiness**: {READY[st.readiness]}")
        if sid in ZS.PROXY:
            out.append(f"- **Vehicle**: {ZS.PROXY[sid]}")
        if sid == "TP-01H":
            out.append("- **This book**: the same rules on 1-hour candles, held overnight (the video names H1 and M5).")
        if title:
            out.append(f"- **Video**: {title}")
        out.extend(bullets)
        out.append("")
    out += ["## Blocked (no account)", ""]
    for bid, name, ch, vids, sect, why in ZS.BLOCKED:
        out.append(f"### {bid} {name} ({', '.join(vids)})")
        out.append("")
        out.append(f"- **Channel**: {ZS.CHANNELS[ch]}")
        out.append(f"- **Section**: {SECTION[sect]}")
        out.append(f"- **Blocked**: {why}")
        out.append("")
    out += ["## Duplicates of the existing library (no account)", ""]
    for vid, ch, what, dup in ZS.DUPLICATES:
        out.append(f"- {vid} ({ZS.CHANNELS[ch]}): {what} - duplicate of {dup}")
    out += ["", "## Second sources merged into a strategy", ""]
    for vid, into, why in ZS.MERGED:
        out.append(f"- {vid} -> {into}: {why}")
    out += ["", "## Not strategies", ""]
    for vid, ch, why in ZS.NOT_STRATEGIES:
        out.append(f"- {vid} ({ZS.CHANNELS[ch]}): {why}")
    (HERE / "specs").mkdir(exist_ok=True)
    (HERE / "specs" / "RULES.md").write_text("\n".join(out) + "\n", encoding="utf-8", newline="\n")
    print("strategies", len(ZS.NEW) - len(missing), "missing", missing)


if __name__ == "__main__":
    main()
