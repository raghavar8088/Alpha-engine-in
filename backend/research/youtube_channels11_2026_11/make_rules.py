"""Writes specs/RULES.md from the channel analyses: per strategy, a heading `### <ID> <name> (<video ids>)` and the
section's rule bullets as they stand in analyses/<channel>.md (E = stated in the video, I = inferred, A = the research
assumption that makes it testable). The paper desk's library cards are built from this file.
    python -I make_rules.py"""

from __future__ import annotations

import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

from yc_strategies import CHANNELS, STRATEGIES  # noqa: E402

VID = re.compile(r"(?<![A-Za-z0-9_-])[A-Za-z0-9_-]{11}(?![A-Za-z0-9_-])")
MARKET = {"NIFTY": "NIFTY index (1-minute data)", "BANKNIFTY": "BANKNIFTY index (1-minute data)",
          "NSE5": "NSE stock pool, 5-minute candles", "NSE15": "NSE stock pool, 15-minute candles",
          "NSED": "NSE stock pool, daily candles", "NIFTY_D": "NIFTY daily candles", "BTCUSD": "Bitcoin (Delta BTCUSD)",
          "XAUUSD": "Gold (Delta XAUTUSD)", "EURUSD": "EUR/USD", "GBPUSD": "GBP/USD", "NAS100": "Nasdaq 100"}


def is_video_id(tok: str) -> bool:
    """An 11-character YouTube id, not an English word of that length: it has a digit, '-' or '_', or mixed case."""
    return any(ch.isdigit() or ch in "-_" for ch in tok) or (tok.lower() != tok and tok.upper() != tok)


def sections(path: Path) -> dict:
    """{strategy id: (heading text, intro lines, bullet lines)} of one analysis file."""
    lines = path.read_text(encoding="utf-8").splitlines()
    out, i = {}, 0
    while i < len(lines):
        m = re.match(r"^## ([A-Z]{2}-\d+)\b(.*)$", lines[i])
        if not m:
            i += 1
            continue
        sid, head = m.group(1), m.group(2).strip()
        i += 1
        while i < len(lines) and (head.count("(") > head.count(")") or lines[i].startswith("(")):
            head += " " + lines[i].strip()                               # a heading that wraps onto the next line
            i += 1
        intro, bullets, started = [], [], False
        while i < len(lines) and not lines[i].startswith("## "):
            ln = lines[i]
            if ln.startswith("- "):
                started = True
                bullets.append(ln)
            elif started and ln.startswith("  ") and ln.strip():
                bullets.append(ln)
            elif started and not ln.strip():
                nxt = lines[i + 1] if i + 1 < len(lines) else ""
                if not nxt.startswith("- "):
                    break                                              # the bullets have ended (other videos follow)
            elif not started and ln.strip():
                intro.append(ln.strip())
            i += 1
        out[sid] = (head, intro, bullets)
    return out


def main():
    all_secs = {}
    for f in sorted((HERE / "analyses").glob("*.md")):
        all_secs.update(sections(f))
    out = ["# The 11-channel study: strategy rules", "",
           "Generated by make_rules.py from analyses/<channel>.md. E = stated or shown in the video (with the time), I =",
           "inferred from the video, A = the research assumption that makes the rule testable. These are paper-test",
           "strategies: no backtest is claimed here.", ""]
    missing = []
    for sid, st in STRATEGIES.items():
        sec = all_secs.get(sid)
        if sec is None:
            missing.append(sid)
            continue
        head, intro, bullets = sec
        groups = " ".join(re.findall(r"\(([^()]*)\)", head))
        vids = list(dict.fromkeys(v for v in VID.findall(groups) if is_video_id(v)))
        out.append(f"### {sid} {st.name} ({', '.join(vids)})")
        out.append("")
        out.append(f"- **Channel**: {CHANNELS[st.channel]}")
        out.append(f"- **Paper desk market**: {'; '.join(MARKET[mk] for mk in st.markets)}")
        text = re.sub(r"\s*(Read|Digests?|Digest read)\b[^.]*\.", "", " ".join(intro)).strip()
        if text:
            out.append(f"- **Video**: {text}")
        out.extend(bullets)
        out.append("")
    (HERE / "specs").mkdir(exist_ok=True)
    (HERE / "specs" / "RULES.md").write_text("\n".join(out) + "\n", encoding="utf-8", newline="\n")
    print("strategies", len(STRATEGIES) - len(missing), "missing", missing)


if __name__ == "__main__":
    main()
