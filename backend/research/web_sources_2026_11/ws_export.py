"""Writes frontend/app/premium-strategies/webSourcesData.ts from registry/candidates.json (generated: never edit the .ts
by hand). Full records for the batch, the variations and the general-market ideas; one line each for the rest.

    python -I ws_export.py
"""

from __future__ import annotations

import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]
OUT = ROOT / "frontend" / "app" / "premium-strategies" / "webSourcesData.ts"
STAT_KEYS = ["trades", "net", "ret_pct", "win_rate", "pf", "max_dd_pct", "exp_pct", "t_stat", "exposure_pct", "ruined_on", "avg_hold_min"]


def stats(s):
    if not s:
        return None
    return {k: (round(v, 3) if isinstance(v, float) else v) for k, v in s.items() if k in STAT_KEYS}


def main() -> None:
    reg = json.loads((HERE / "registry" / "candidates.json").read_text(encoding="utf-8"))
    full, brief = [], []
    for c in reg["candidates"]:
        src = c.get("source", {})
        base = {"sid": c["sid"], "name": c["name"], "group": c["group"], "status": c["status"], "rank": c["rank"],
                "reason": c.get("status_reason", ""), "url": src.get("url", ""), "platform": src.get("platform", ""),
                "batch": bool(c.get("batch"))}
        if c.get("batch") or c.get("variation_of") or c["group"] == "general" and c.get("rules"):
            r = c.get("results") or {}
            base.update({
                "variationOf": c.get("variation_of"), "kind": c.get("kind", ""),
                "source": {k: src.get(k) for k in ("platform", "url", "author", "retrieved", "licence", "version", "file_sha256", "post_published") if src.get(k)},
                "market": c.get("market", {}), "hypothesis": (c.get("hypothesis") or {}).get("text", ""),
                "rules": [{"kind": x["kind"], "tag": x["tag"], "text": x["text"], "loc": x["loc"], "quote": x.get("quote", "")[:360]} for x in c.get("rules", [])],
                "missing": c.get("missing", []), "claims": [x["text"] for x in c.get("claims", [])],
                "risks": [{"check": x["check"], "finding": x["finding"]} for x in c.get("risks", [])],
                "dedupe": c.get("dedupe", {}), "more": c.get("sources_more", []), "blocker": c.get("blocker"),
                "gate": c.get("gate", []),
                "results": None if not r else {
                    "market": r.get("market"), "labels": r.get("labels"), "dev": stats(r.get("dev")), "oos": stats(r.get("oos")),
                    # gold's 'other window' is shown as its own row ("After the post"), so no second-market row there
                    "oosX2": stats(r.get("oos_x2")), "second": stats(r.get("oos_second")), "secondMarket": r.get("second_market", "ETH/USDT" if c["group"] == "crypto" else None),
                    "post": stats(r.get("post")), "perp": stats(((r.get("perp_adaptation") or {}) or {}).get("oos")),
                    "bhOos": r.get("oos_buy_hold_pct"), "bhDev": r.get("dev_buy_hold_pct"), "yearly": r.get("yearly"),
                    "sens": r.get("sensitivity")},
            })
            full.append(base)
        else:
            brief.append(base)
    meta = {"built": reg["built"], "retrieved": reg["retrieved"], "commit": reg["freqtrade_commit"], "gate": reg["gate"],
            "counts": reg["counts"], "screened": reg["screened"]}
    ts = ["// Generated by backend/research/web_sources_2026_11/ws_export.py from registry/candidates.json - do not edit by hand.",
          "// Crypto and gold strategies collected from public web sources (freqtrade-strategies, QuantConnect, broker and",
          "// trading-education guides): rules with evidence, implementation-risk checks and fee-honest backtests. Research only.",
          "export type WsStats = { trades: number; net?: number; ret_pct?: number; win_rate?: number; pf?: number | null; max_dd_pct?: number; exp_pct?: number; t_stat?: number | null; exposure_pct?: number; ruined_on?: string | null; avg_hold_min?: number };",
          "export type WsRule = { kind: string; tag: string; text: string; loc: string; quote: string };",
          "export type WsRecord = { sid: string; name: string; group: string; status: string; rank: number; reason: string; url: string; platform: string; batch: boolean;",
          "  variationOf?: string | null; kind?: string; source?: Record<string, string>; market?: Record<string, string>; hypothesis?: string; rules?: WsRule[];",
          "  missing?: string[]; claims?: string[]; risks?: { check: string; finding: string }[]; dedupe?: { verdict?: string; note?: string };",
          "  more?: { url: string; note: string }[]; blocker?: string | null; gate?: { check: string; pass: boolean | null }[];",
          "  results?: { market?: string; labels?: Record<string, string> | null; dev?: WsStats | null; oos?: WsStats | null; oosX2?: WsStats | null; second?: WsStats | null;",
          "    secondMarket?: string | null; post?: WsStats | null; perp?: WsStats | null; bhOos?: number | null; bhDev?: number | null; yearly?: Record<string, number> | null;",
          "    sens?: Record<string, { dev_net: number | null; oos_net: number | null; dev_trades?: number | null; oos_trades?: number | null }> | null } | null };",
          f"export const WS_META = {json.dumps(meta, ensure_ascii=False)} as const;",
          f"export const WS: WsRecord[] = {json.dumps(full, ensure_ascii=False)};",
          f"export const WS_OTHER: WsRecord[] = {json.dumps(brief, ensure_ascii=False)};", ""]
    OUT.write_text("\n".join(ts), encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)}: {len(full)} full records, {len(brief)} brief, {OUT.stat().st_size // 1024} KB")


if __name__ == "__main__":
    main()
