"""Write REPORT.md from validation_report.json, so no number in it is typed by hand."""
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
r = json.load(open(HERE / "validation_report.json", encoding="utf-8"))
H = {"1d": "1 day", "1w": "1 week", "1m": "1 month", "3m": "3 months"}
SIG = {"mom_12_1": "12-1 month momentum", "rev_1m": "1-month reversal", "prox_52w": "52-week-high proximity",
       "low_vol": "low volatility"}


def pct(v, d=1):
    return "—" if v is None else f"{v * 100:.{d}f}%"


lines = []
w = lines.append
d = r["data"]
w("# NSE Stock Ratings: forward-return estimates, validation report")
w("")
w(f"Generated by `validate.py` from {d['sessions']:,} NSE sessions ({d['first']} to {d['last']}), "
  f"{d['symbols']:,} symbols, closes adjusted for {d['adjusted_actions']} bonuses, splits and "
  f"consolidations, with {d['breaks']} breaks (unadjustable corporate actions and one-day moves "
  "outside every NSE price band) excluded from every return.")
w("")
w(f"Training (fitting) window: {d['train'][0]} to {d['train'][1]}. Hold-out (judging) window: "
  f"{d['test'][0]} to {d['test'][1]}. Every rule below was written into `validate.py` before its "
  "result was seen, and nothing was refitted on the hold-out.")
w("")
w("## What the estimate is")
w("")
w("For horizon h, the log return is modelled as mu + z * sigma. Sigma is the stock's own daily "
  "volatility, a blend of a fast EWMA and its one-year level with the blend weight chosen per horizon, "
  "times sqrt(h). Mu is India's long-run market drift (ln 1.11 a year). z comes from the empirical "
  "quantiles of standardised outcomes, pooled across stocks and re-centred on 0 so the training "
  "window's own drift is not carried forward. Bear and bull are the 10th and 90th percentiles, the "
  "base case is the median, and the downside is the 5th percentile.")
w("")
w("## Did the ranges hold? (pass bar: 80% range holds 75-85%, 1-in-20 downside breached 3-8%)")
w("")
w("| Horizon | EWMA weight | 80% range held | 1-in-20 downside breached | Outcomes above base | Median outcome | Base case | Plain normal model, range held | Verdict |")
w("|---|---|---|---|---|---|---|---|---|")
for hk, h in r["horizons"].items():
    te = h["test"]
    w(f"| {H[hk]} | {h['ewma_weight']} | {pct(te['coverage_80'])} | {pct(te['below_p05'])} | "
      f"{pct(te['above_base'], 0)} | {te['median_outcome_pct']:+.2f}% | {te['base_pct']:+.2f}% | "
      f"{pct(h['naive_test']['coverage_80'])} | {'passed' if h['passed'] else 'missed'} |")
w("")
w("The hold-out was a falling market for most NSE stocks: the median 3-month outcome was "
  f"{r['horizons']['3m']['test']['median_outcome_pct']:+.1f}% against a base case of "
  f"{r['horizons']['3m']['test']['base_pct']:+.1f}%. The 80% ranges held a little under target, and "
  "the downside was breached more often than the 5% it claims, because the training window (a broad "
  "rally) had thinner downside tails. So, by the rule written before the run, every estimate for a "
  "horizon that missed is shown at **low confidence**, with the breach rate quoted. The 1-day "
  "horizon passed.")
w("")
w("## Did any price signal predict? (rule: rank IC with |t| >= 2, same sign, in BOTH periods)")
w("")
w("| Horizon | Signal | Train IC (t) | Hold-out IC (t) | Passes |")
w("|---|---|---|---|---|")
for hk, sg in r["signals"].items():
    for n, x in sg.items():
        tr, te = x["train"], x["test"]
        w(f"| {H[hk]} | {SIG[n]} | {tr['mean_ic']:+.3f} ({tr['t']:+.1f}) | {te['mean_ic']:+.3f} ({te['t']:+.1f}) | "
          f"{'yes' if x['passes'] else 'no'} |")
w("")
w("Momentum, closeness to the 52-week high and low volatility ranked later returns in both periods. "
  "A one-month reversal did not. Each passing signal was then tried as a tilt on the base case: "
  "the mean of its percentiles, centred, times a slope fitted by OLS on the training window only. "
  "The tilt was kept only where it lowered the hold-out pinball loss.")
w("")
w("| Horizon | Signals | Slope (train) | Kept | Untilted pinball | Tilted pinball |")
w("|---|---|---|---|---|---|")
for hk, h in r["horizons"].items():
    t = h["tilt"]
    w(f"| {H[hk]} | {', '.join(SIG[s] for s in t['signals']) or '—'} | {t['beta_train']:+.4f} | "
      f"{'yes' if t['kept'] else 'no'} | {t['untilted_test']['pinball']:.6f} | {t['tilted_test']['pinball']:.6f} |")
w("")
for hk in ("1m", "3m"):
    q = r["horizons"][hk]["tilt"]["quintiles_test"]
    if not q:
        continue
    w(f"**{H[hk]}, hold-out, by signal quintile** (1 = weakest):")
    w("")
    w("| Quintile | Stocks x dates | Predicted median | Realised median | Realised mean |")
    w("|---|---|---|---|---|")
    for x in q:
        w(f"| {x['quintile']} | {x['n']:,} | {x['predicted_median_pct']:+.2f}% | {x['realized_median_pct']:+.2f}% | "
          f"{x['realized_mean_pct']:+.2f}% |")
    w("")
w("The ordering held: the strongest quintile beat the weakest by several points. The level did not: "
  "in a falling market, every quintile came in below its predicted median. The tilt tells you which "
  "stocks the evidence leans towards, not that any of them will rise.")
w("")
w("## What ships")
w("")
w("`app/data/nse_forecast_calibration.json` holds the chosen model refitted on ALL outcomes (Nov "
  "2022 to Nov 2026), so its tails include the 2024-26 decline as well as the 2022-24 rally. Confidence on "
  "the page comes from the hold-out results above, by liquidity and volatility bucket, and is never "
  "better than the horizon's own verdict. A stock gets no estimate (\"Insufficient data\") with "
  "fewer than 120 daily returns in a year, no trade on more than 25% of the last 63 sessions, no "
  "trade in the last 3 sessions, a BZ-series listing, or an unadjustable corporate action in the "
  "last 3 months.")
w("")
w("These are estimates of a range, from history. They are not predictions, targets or advice.")

(HERE / "REPORT.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
print("wrote", HERE / "REPORT.md", len(lines), "lines")
