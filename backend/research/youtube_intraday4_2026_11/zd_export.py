"""Writes frontend/app/premium-strategies/intraday4Data.ts: every strategy of the four-topic intraday study with its
video, rules (tagged E / I / A with their times), what is missing or ambiguous, the claims as said, the status (coded,
blocked or duplicate) and the look-ahead / fill check of the coded ones (results/checks.json). Generated: never edit
the .ts by hand.      python -I zd_export.py
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]
sys.path.insert(0, str(HERE))

import zd_cardlib as CL  # noqa: E402
import zd_strategies as ZS  # noqa: E402

OUT = ROOT / "frontend" / "app" / "premium-strategies" / "intraday4Data.ts"
MARKET_LABEL = {"NIFTY": "NIFTY 50", "BANKNIFTY": "Bank Nifty", "NSE5": "NSE stocks (5-minute pool)",
                "NSE15": "NSE stocks (15-minute bars)", "BTCUSD": "Bitcoin (BTCUSD)", "MCXCRUDE": "MCX Crude Oil",
                "MCXNG": "MCX Natural Gas", "MCXSILVER": "MCX Silver Micro"}
PROXY = {"OB": "the video buys NIFTY options; coded on the NIFTY index as a labelled proxy (the desk has no intraday "
               "option premiums)",
         "SI-01": "the video buys ATM stock options; coded on the stock itself"}


def main():
    checks = {}
    cp = HERE / "results" / "checks.json"
    if cp.exists():
        checks = json.loads(cp.read_text())["results"]
    pool = json.loads((HERE / "registry" / "pool.json").read_text(encoding="utf-8"))
    rows = []
    for c in CL.all_cards():
        meta = CL.video_meta(c["video"])
        for s in c["strategies"]:
            sid = s["sid"]
            rec = ZS.YS.STRATEGIES.get(sid) if sid in ZS.NEW else None
            if s["duplicate"]:
                status = "duplicate"
            elif sid in ZS.BLOCKED:
                status = "blocked"
            else:
                status = "coded"
            ch = checks.get(sid) or {}
            rows.append({
                "id": sid, "version": "v1", "name": s["name"], "topic": c["topic"],
                "status": status, "readiness": "ready" if s["status"] == "ready" else "assumptions",
                "cardStatus": s["status"], "channel": meta["channel"], "video": c["video"], "title": meta["title"],
                "uploaded": meta["uploaded"], "minutes": meta["minutes"], "summary": c["summary"],
                "instruments": c["instruments"], "timeframes": c["timeframes"],
                "markets": [MARKET_LABEL.get(x, x) for x in (rec.markets if rec else ())],
                "deskMarkets": list(rec.markets) if rec else [],
                "overnight": bool(rec.overnight) if rec else False,
                "proxy": PROXY.get(sid) or (PROXY["OB"] if sid.startswith("OB-") and status == "coded" else None),
                "rules": [{"kind": r["kind"], "label": CL.KIND_LABEL[r["kind"]], "tag": r["tag"], "text": r["text"],
                           "times": r["times"]} for r in sorted(s["rules"], key=lambda r: (r["tag"] == "A", CL.KINDS_ORDER.index(r["kind"])))],
                "why": s["reasons"],
                "vague": c["vague"], "unclear": c["unclear"], "claims": c["claims"], "examples": c["examples"],
                "blockedReason": ZS.BLOCKED.get(sid), "duplicateOf": s["duplicate"]["of"] if s["duplicate"] else None,
                "duplicateWhy": s["duplicate"]["why"] if s["duplicate"] else None,
                "checks": ({"lookahead": bool(ch.get("lookahead_ok")), "fills": not ch.get("fill_problems"),
                            "signals": int(ch.get("signals", 0)), "trades": int(ch.get("trades", 0))} if ch else None),
            })
    rows.sort(key=lambda r: (["nifty_option_buying", "stock_intraday", "btc_intraday", "commodity_intraday"].index(r["topic"]), r["id"]))
    covered = sum(1 for r in pool if r.get("covered"))
    sel = 0
    for f in (HERE / "catalogue" / "selection").glob("*.tsv"):
        sel += sum(1 for line in f.read_text(encoding="utf-8").splitlines()[1:] if "\tprimary\t" in line)
    coded = [r for r in rows if r["status"] == "coded"]
    meta = {"queries": 40, "found": len(pool), "covered_before": covered, "selected": sel,
            "backups_queued": 16, "analysed": len({r["video"] for r in rows}), "strategies": len(rows),
            "coded": len(coded), "blocked": sum(1 for r in rows if r["status"] == "blocked"),
            "duplicates": sum(1 for r in rows if r["status"] == "duplicate"),
            "lookahead_ok": sum(1 for r in coded if r["checks"] and r["checks"]["lookahead"] and r["checks"]["fills"]),
            "built": "2026-11-12"}
    head = (
        "// GENERATED by backend/research/youtube_intraday4_2026_11/zd_export.py - do not edit by hand.\n"
        "// The four-topic intraday study (Nov 2026): NIFTY option buying, NSE stock intraday, bitcoin and MCX commodity\n"
        "// intraday strategies from YouTube, each with its rules (E stated / I inferred / A our assumption, with the video\n"
        "// times), what the video leaves missing or vague, its claims as said, and its status and code checks.\n\n"
        "export type I4Rule = { kind: string; label: string; tag: \"E\" | \"I\" | \"A\"; text: string; times: string[] };\n"
        "export type I4Vague = { term: string; rule: string; at: string; why: string; suggestion: string };\n"
        "export type I4Claim = { kind: string; at: string; value: string; period: string; quote: string };\n"
        "export type I4Example = { date: string; at: string; instrument: string; direction: string; setup: string; entry: string;\n"
        "  stop: string; target: string; outcome: string; note: string };\n"
        "export type I4Strategy = { id: string; version: string; name: string; topic: string; status: \"coded\" | \"blocked\" | \"duplicate\";\n"
        "  readiness: \"ready\" | \"assumptions\"; cardStatus: string; channel: string; video: string; title: string; uploaded: string;\n"
        "  minutes: number; summary: string; instruments: string[]; timeframes: string[]; markets: string[]; deskMarkets: string[];\n"
        "  overnight: boolean; proxy: string | null; rules: I4Rule[]; why: string[]; vague: I4Vague[]; unclear: string[];\n"
        "  claims: I4Claim[]; examples: I4Example[]; blockedReason: string | null; duplicateOf: string | null; duplicateWhy: string | null;\n"
        "  checks: { lookahead: boolean; fills: boolean; signals: number; trades: number } | null };\n\n")
    body = (f"export const I4_META = {json.dumps(meta)};\n\n"
            f"export const I4: I4Strategy[] = {json.dumps(rows, ensure_ascii=False, indent=1)};\n")
    OUT.write_text(head + body, encoding="utf-8")
    print("wrote", OUT, "strategies", len(rows), "coded", len(coded), meta)


if __name__ == "__main__":
    main()
