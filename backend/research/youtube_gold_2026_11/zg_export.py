"""Writes the app's data for the Gold tab's "Gold channels 21-40" section (frontend/app/premium-strategies/goldYtData.ts)
and the readable analysis (analyses/gold_channels_21_40.md) from zg_spec.py, with each video's title, date and length
from the Trading Video Lab's evidence and each coded strategy's code check (results/checks.json). Generated: never edit
the outputs by hand.

    python -I zg_export.py
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]
sys.path.insert(0, str(HERE))

import zg_spec as S  # noqa: E402
import zg_strategies as ZG  # noqa: E402

OUT_TS = ROOT / "frontend" / "app" / "premium-strategies" / "goldYtData.ts"
OUT_MD = HERE / "analyses" / "gold_channels_21_40.md"
LAB = ROOT / "youtube-video-explainer-reviewed" / "evidence"


def meta(vid: str) -> dict:
    folders = sorted(LAB.glob(f"{vid}-*"), key=lambda p: p.name)
    for f in reversed(folders):
        mf = f / "manifest.json"
        if mf.exists():
            j = json.loads(mf.read_text(encoding="utf-8"))
            mm = j.get("meta") or {}
            up = mm.get("upload_date") or ""
            if len(up) == 8 and up.isdigit():
                up = f"{up[:4]}-{up[4:6]}-{up[6:]}"
            return {"title": j.get("title") or mm.get("title") or "", "uploaded": up,
                    "minutes": round(float(j.get("duration") or 0) / 60), "captions": (j.get("transcript") or {}).get("source") or ""}
    return {"title": "", "uploaded": "", "minutes": 0, "captions": ""}


def short(t: str) -> str:
    h, m, s = (int(x) for x in t.split(":"))
    return f"{m:02d}:{s:02d}" if h == 0 else f"{h}:{m:02d}:{s:02d}"


def tm(c) -> dict | None:
    return None if not c else {"v": c[0], "t": short(c[1])}


def main() -> None:
    checks = json.loads((HERE / "results" / "checks.json").read_text())["results"]
    reg = {r.sid: r for r in ZG._NEW}
    vids = {v: meta(v) for v, _k, _w in S.VIDEOS}
    strategies = []
    for s in S.STRATEGIES:
        m = vids.get(s["video"]) or meta(s["video"])
        c = checks.get(s["id"], {})
        r = reg[s["id"]]
        strategies.append({
            "id": s["id"], "version": r.version, "name": s["name"], "full": r.name, "status": "coded",
            "readiness": r.readiness, "channel": s["channel"], "video": s["video"], "title": m["title"],
            "uploaded": m["uploaded"], "minutes": m["minutes"], "summary": s["summary"], "timeframes": s["timeframes"],
            "overnight": bool(r.overnight), "market": "Gold (Delta Exchange XAUTUSD)",
            "rules": [{"kind": x["kind"], "label": x["label"], "tag": x["tag"], "text": x["text"], "quote": x["quote"],
                       "times": [tm(t) for t in x["times"]]} for x in s["rules"]],
            "vague": [{"term": v[0], "at": tm(v[1]), "why": v[2], "coded": v[3]} for v in s.get("vague", [])],
            "claims": [{"value": c2[0], "at": tm(c2[1])} for c2 in s.get("claims", [])],
            "cites": [{"v": v, "title": (vids.get(v) or meta(v))["title"]} for v in s.get("cites", [])],
            "duplicateCheck": s["duplicateCheck"], "paperStart": S.PAPER_START,
            "checks": {"lookahead": bool(c.get("lookahead_ok")), "fills": not c.get("fill_problems"),
                       "signals": int(c.get("signals", 0)), "trades": int(c.get("trades", 0))},
        })
    not_coded = [{"id": i, "name": n, "channel": ch, "videos": [{"v": v, "title": (vids.get(v) or meta(v))["title"]} for v in vs],
                  "status": st, "reason": why, "duplicateOf": dup} for i, n, ch, vs, st, why, dup in S.NOT_CODED]
    by_chan: dict = {}
    for v, k, what in S.VIDEOS:
        by_chan.setdefault(k, []).append({"id": v, **vids[v], "what": what})
    coded_by = {}
    for s in strategies:
        coded_by.setdefault(s["channel"], []).append(s["id"])
    channels = [{"pos": pos, "key": k, "name": nm, "channelId": cid, "earlier": earlier, "listed": listed,
                 "videos": by_chan.get(k, []), "coded": coded_by.get(nm, [])}
                for pos, k, nm, cid, earlier, listed in S.CHANNELS]
    read = sum(1 for v in vids.values() if v["captions"])
    meta_out = {"built": S.BUILT, "paperStart": S.PAPER_START, "channels": len(S.CHANNELS), "videos": len(S.VIDEOS),
                "read": read, "coded": len(strategies), "notCoded": len(not_coded),
                "blocked": sum(1 for x in not_coded if x["status"] == "blocked"),
                "duplicates": sum(1 for x in not_coded if x["status"] == "duplicate"),
                "concept": sum(1 for x in not_coded if x["status"] == "concept"),
                "checked": sum(1 for s in strategies if s["checks"]["lookahead"] and s["checks"]["fills"]),
                "capital": 1000000, "source": ZG.SOURCE}
    head = ("// GENERATED by backend/research/youtube_gold_2026_11/zg_export.py - do not edit by hand.\n"
            "// Gold channels 21-40 (the owner's list, 22 Nov 2026): every channel and video read, the strategies found with their\n"
            "// rules (E stated / I inferred / A our assumption, each stated rule with its quote and video time), what was not coded\n"
            "// and why, and the code checks of the coded ones. Each coded strategy paper trades Rs 10 lakh on Delta XAUTUSD.\n\n")
    types = (
        "export type GyTime = { v: string; t: string };\n"
        "export type GyRule = { kind: string; label: string; tag: \"E\" | \"I\" | \"A\"; text: string; quote: string; times: (GyTime | null)[] };\n"
        "export type GyStrategy = { id: string; version: string; name: string; full: string; status: \"coded\"; readiness: string;\n"
        "  channel: string; video: string; title: string; uploaded: string; minutes: number; summary: string; timeframes: string[];\n"
        "  overnight: boolean; market: string; rules: GyRule[]; vague: { term: string; at: GyTime | null; why: string; coded: string }[];\n"
        "  claims: { value: string; at: GyTime | null }[]; cites: { v: string; title: string }[]; duplicateCheck: string;\n"
        "  paperStart: string; checks: { lookahead: boolean; fills: boolean; signals: number; trades: number } };\n"
        "export type GyNotCoded = { id: string; name: string; channel: string; videos: { v: string; title: string }[];\n"
        "  status: \"blocked\" | \"duplicate\" | \"concept\"; reason: string; duplicateOf: string | null };\n"
        "export type GyVideo = { id: string; title: string; uploaded: string; minutes: number; captions: string; what: string };\n"
        "export type GyChannel = { pos: number; key: string; name: string; channelId: string; earlier: string; listed: string;\n"
        "  videos: GyVideo[]; coded: string[] };\n\n")
    body = (f"export const GY_META = {json.dumps(meta_out)};\n"
            f"export const GY: GyStrategy[] = {json.dumps(strategies, indent=1, ensure_ascii=False)};\n"
            f"export const GY_NOT: GyNotCoded[] = {json.dumps(not_coded, indent=1, ensure_ascii=False)};\n"
            f"export const GY_CHANNELS: GyChannel[] = {json.dumps(channels, indent=1, ensure_ascii=False)};\n")
    OUT_TS.write_text(head + types + body, encoding="utf-8", newline="\n")
    print("wrote", OUT_TS, OUT_TS.stat().st_size, "bytes")

    lines = [f"# Gold channels 21-40 ({S.BUILT})", "",
             f"{meta_out['channels']} channels, {meta_out['videos']} videos picked, {read} read from their captions. "
             f"{meta_out['coded']} strategies coded (version v1, Rs 10 lakh each on Delta XAUTUSD from {S.PAPER_START}), "
             f"{meta_out['notCoded']} methods not coded ({meta_out['blocked']} need data the desk lacks or paid tools, "
             f"{meta_out['duplicates']} repeat another, {meta_out['concept']} teach no testable rule). None was backtested.", ""]
    for s in strategies:
        lines += [f"## {s['id']} {s['name']}", f"{s['channel']} - https://youtu.be/{s['video']} ({s['title']})", "", s["summary"], ""]
        for x in s["rules"]:
            t = ", ".join(f"{q['v']} {q['t']}" for q in x["times"] if q)
            lines.append(f"- [{x['tag']}] {x['label']}: {x['text']}" + (f" \"{x['quote']}\" ({t})" if x["quote"] else ""))
        lines += ["", f"Code check: look-ahead {'ok' if s['checks']['lookahead'] else 'FAILED'}, fills "
                  f"{'ok' if s['checks']['fills'] else 'FAILED'}; {s['checks']['signals']} signals, {s['checks']['trades']} simulated fills on research data.", ""]
    lines += ["## Not coded", ""]
    for x in not_coded:
        lines.append(f"- {x['id']} {x['name']} ({x['channel']}): {x['status']} - {x['reason']}")
    OUT_MD.parent.mkdir(exist_ok=True)
    OUT_MD.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print("wrote", OUT_MD)


if __name__ == "__main__":
    main()
