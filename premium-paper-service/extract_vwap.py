def block(lines, start, stop):
    """From the line starting with `start` up to, not including, the line starting with `stop`."""
    a = next(i for i, x in enumerate(lines) if x.startswith(start))
    b = next(i for i, x in enumerate(lines) if i > a and x.startswith(stop))
    return lines[a:b]


